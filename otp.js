    /* =====================================================
       REQUEST BACKEND OTP
       ===================================================== */

    async function requestBackendOtp(
        mode = "prepare"
    ) {

        if (!API) {

            throw new Error(
                "StockFlowAPI is not available."
            );
        }


        const identity =
            resolveIdentity();


        if (!identity) {

            throw new Error(
                "Username or Gmail is required."
            );
        }


        saveState();


        const payload = {

            uid:
                state.uid,

            identity:
                identity,

            username:
                state.username,

            email:
                state.email,

            gmail:
                state.email,

            phone:
                state.phone,

            channel:
                state.channel
        };


        if (
            mode === "resend"
        ) {

            return await API.resendOtp(
                payload
            );
        }


        return await API.prepareOtp(
            payload
        );
    }


    /* =====================================================
       SYNCHRONIZE BACKEND ACCOUNT DATA
       ===================================================== */

    function synchronizeBackendData(
        response
    ) {

        const data =
            getResponseData(
                response
            );


        state.uid =
            firstValue(
                data.uid,
                data.UID,
                state.uid
            );


        state.username =
            firstValue(
                data.username,
                data.USERNAME,
                state.username
            );


        state.email =
            firstValue(
                data.email,
                data.gmail,
                data.GMAIL,
                state.email
            );


        state.phone =
            firstValue(
                data.phone,
                data.phoneNumber,
                data["PHONE NO."],
                state.phone
            );


        state.identity =
            firstValue(
                data.identity,
                state.identity,
                state.username,
                state.email,
                state.phone,
                state.uid
            );


        /*
         * If backend explicitly returns the channel,
         * synchronize it too.
         */

        const returnedChannel =
            clean(
                data.channel
            ).toLowerCase();


        if (
            returnedChannel === "email" ||
            returnedChannel === "phone"
        ) {

            state.channel =
                returnedChannel;
        }


        saveState();
    }


    /* =====================================================
       PREPARE INITIAL OTP
       ===================================================== */

    async function prepareOtp() {

        if (
            state.preparing
        ) {

            return;
        }


        /*
         * If an OTP is already visibly prepared,
         * do not automatically generate another one.
         */

        if (
            state.prepared &&
            state.backendOtp
        ) {

            return;
        }


        state.preparing =
            true;


        displayPreparingMessage();


        try {

            /*
             * Initial preparation uses the currently
             * selected channel.
             *
             * Default is email.
             */

            const response =
                await requestBackendOtp(
                    "prepare"
                );


            const data =
                getResponseData(
                    response
                );


            if (
                !isResponseSuccessful(
                    response
                )
            ) {

                throw createApiError(
                    data
                );
            }


            synchronizeBackendData(
                response
            );


            displayDestinations();


            /*
             * ONLY accept the actual OTP returned
             * from Code.gs.
             */

            const backendOtp =
                extractBackendOtp(
                    response
                );


            if (!backendOtp) {

                throw new Error(
                    "The verification service did not return the generated OTP."
                );
            }


            const stored =
                storeBackendOtp(
                    backendOtp
                );


            if (!stored) {

                throw new Error(
                    "The backend returned an invalid verification code."
                );
            }


            /*
             * Keep boxes disabled until the display delay
             * has completed.
             */

            disableOtpInputs();


            clearVisibleOtp();


            if (otpHelp) {

                otpHelp.textContent =
                    "Your verification code is being prepared...";
            }


            /*
             * Start cooldown after successful backend
             * OTP generation.
             *
             * This applies only to the selected channel.
             *
             * Email and phone cooldowns remain independent.
             */

            startCooldown(
                state.channel
            );


            /*
             * Fixed 4-second display delay.
             *
             * No OTP generation occurs here.
             */

            const delayMs =
                getOtpDisplayDelay();


            state.otpDisplayTimer =
                setTimeout(
                    function () {

                        state.otpDisplayTimer =
                            null;


                        displayBackendOtp(
                            backendOtp
                        );

                    },
                    delayMs
                );


        } catch (error) {

            console.error(
                "[STOCKFLOW OTP] Prepare failed:",
                error
            );


            state.prepared =
                false;


            clearBackendOtp();


            disableOtpInputs();


            showMessage(
                getErrorMessage(
                    error
                ),
                "error"
            );


            if (otpHelp) {

                otpHelp.textContent =
                    "We could not prepare your verification code. Please try again.";
            }

        } finally {

            state.preparing =
                false;


            updateResendButtons();
        }
    }


    /* =====================================================
       SEND / RESEND CODE
       ===================================================== */

    async function sendCode(
        channel
    ) {

        if (
            channel !== "email" &&
            channel !== "phone"
        ) {

            return;
        }


        if (
            state.resending ||
            state.preparing
        ) {

            return;
        }


        /*
         * Validate destination.
         */

        if (
            channel === "email" &&
            !state.email
        ) {

            showMessage(
                "No Gmail address is available for this account.",
                "error"
            );


            return;
        }


        if (
            channel === "phone" &&
            !state.phone
        ) {

            showMessage(
                "No mobile number is available for this account.",
                "error"
            );


            return;
        }


        const cooldown =
            channel === "email"
                ? state.emailCooldown
                : state.phoneCooldown;


        if (
            cooldown > 0
        ) {

            showMessage(
                "Please wait " +
                cooldown +
                " seconds before requesting another code.",
                "warning"
            );


            return;
        }


        /*
         * Select requested channel.
         */

        setActiveChannel(
            channel
        );


        state.resending =
            true;


        const button =
            channel === "email"
                ? emailResendButton
                : phoneResendButton;


        setButtonLoading(
            button,
            true,
            "Preparing..."
        );


        hideMessage();


        /*
         * Cancel previous display timer.
         */

        if (
            state.otpDisplayTimer
        ) {

            clearTimeout(
                state.otpDisplayTimer
            );


            state.otpDisplayTimer =
                null;
        }


        /*
         * The previous OTP must never remain visible.
         */

        clearBackendOtp();


        clearVisibleOtp();


        disableOtpInputs();


        if (otpHelp) {

            otpHelp.textContent =
                "Preparing your new verification code...";
        }


        try {

            const response =
                await requestBackendOtp(
                    "resend"
                );


            const data =
                getResponseData(
                    response
                );


            if (
                !isResponseSuccessful(
                    response
                )
            ) {

                throw createApiError(
                    data
                );
            }


            synchronizeBackendData(
                response
            );


            /*
             * Make sure backend response corresponds to
             * the channel requested by the user.
             */

            const responseChannel =
                clean(
                    data.channel
                ).toLowerCase();


            if (
                responseChannel === "email" ||
                responseChannel === "phone"
            ) {

                state.channel =
                    responseChannel;


                saveValue(
                    KEY.CHANNEL,
                    responseChannel
                );
            }


            displayDestinations();


            /*
             * ONLY accept backend-generated OTP.
             */

            const backendOtp =
                extractBackendOtp(
                    response
                );


            if (!backendOtp) {

                throw new Error(
                    "The verification service did not return the new generated OTP."
                );
            }


            const stored =
                storeBackendOtp(
                    backendOtp
                );


            if (!stored) {

                throw new Error(
                    "The backend returned an invalid verification code."
                );
            }


            if (otpHelp) {

                otpHelp.textContent =
                    "Your new verification code is being prepared...";
            }


            /*
             * Fixed 4-second display delay.
             *
             * No OTP generation happens here.
             */

            const delayMs =
                getOtpDisplayDelay();


            state.otpDisplayTimer =
                setTimeout(
                    function () {

                        state.otpDisplayTimer =
                            null;


                        displayBackendOtp(
                            backendOtp
                        );

                    },
                    delayMs
                );


            /*
             * Cooldown begins only after Code.gs
             * successfully generates the new OTP.
             */

            startCooldown(
                channel
            );


        } catch (error) {

            console.error(
                "[STOCKFLOW OTP] Resend failed:",
                error
            );


            /*
             * Do not leave an invalid/stale OTP in
             * browser storage after a failed request.
             */

            clearBackendOtp();


            clearVisibleOtp();


            disableOtpInputs();


            showMessage(
                getErrorMessage(
                    error
                ),
                "error"
            );


            if (otpHelp) {

                otpHelp.textContent =
                    "We could not generate a new verification code. Please try again.";
            }

        } finally {

            state.resending =
                false;


            setButtonLoading(
                button,
                false
            );


            updateResendButtons();
        }
    }


