    /* =====================================================
       INITIALIZE METHOD CARDS
       ===================================================== */

    function initializeMethodCards() {

        const cards =
            getMethodCards();


        cards.forEach(
            function (
                card
            ) {

                const channel =
                    card.dataset
                        .verificationMethod;


                if (
                    channel !== "email" &&
                    channel !== "phone"
                ) {

                    return;
                }


                card.setAttribute(
                    "role",
                    "button"
                );


                card.setAttribute(
                    "tabindex",
                    "0"
                );


                /*
                 * IMPORTANT:
                 *
                 * Clicking the card ONLY selects the method.
                 *
                 * It does NOT generate a new OTP.
                 *
                 * The button inside the card performs the
                 * actual OTP request.
                 */

                card.addEventListener(
                    "click",
                    function (
                        event
                    ) {

                        if (
                            event.target.closest(
                                "button"
                            )
                        ) {

                            return;
                        }


                        setActiveChannel(
                            channel
                        );


                        hideMessage();
                    }
                );


                card.addEventListener(
                    "keydown",
                    function (
                        event
                    ) {

                        if (
                            event.key === "Enter" ||
                            event.key === " "
                        ) {

                            event.preventDefault();


                            setActiveChannel(
                                channel
                            );


                            hideMessage();
                        }
                    }
                );
            }
        );


        setActiveChannel(
            state.channel
        );
    }


