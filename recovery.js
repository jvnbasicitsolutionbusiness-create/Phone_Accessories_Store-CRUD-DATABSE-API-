    async function initialize() {

        loadSavedState();


        initializeOtpInputs();


        initializePasswordToggles();


        initializeEvents();


        displayDestination();


        showStep(
            "otp"
        );


        disableOtpInputs();


        /*
         * IMPORTANT:
         *
         * If forgot-password.js already requested
         * the OTP, DO NOT request another OTP.
         */

        const recoveryReady =
            storageGet(
                STORAGE_KEYS.RECOVERY_READY
            );


        if (
            recoveryReady === "true" &&
            state.backendOtp
        ) {

            prepareExistingOtp();

            return;
        }


        /*
         * If we arrive here with an identity but
         * without a prepared OTP, request one.
         */

        if (
            resolveIdentity()
        ) {

            await requestRecoveryOtp();

            return;
        }


        showMessage(
            recoveryMessage,
            "Enter your registered Gmail, phone number, or username to begin account recovery.",
            "info"
        );
    }


