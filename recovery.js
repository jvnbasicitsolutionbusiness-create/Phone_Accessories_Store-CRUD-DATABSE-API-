    /* =====================================================
       ERROR HANDLING
       ===================================================== */

    function getErrorCode(error) {

        return clean(
            error &&
            (
                error.code ||
                error.errorCode ||
                error.statusCode
            )
        ).toUpperCase();
    }


    function getErrorMessage(error) {

        if (!error) {

            return (
                "Something went wrong. Please try again."
            );
        }


        const code =
            getErrorCode(error);


        const message =
            clean(
                error.message
            );


        /*
         * Account errors.
         */

        if (
            code === "USER_NOT_FOUND" ||
            code === "ACCOUNT_NOT_FOUND" ||
            code === "RECOVERY_USER_NOT_FOUND"
        ) {

            return (
                "No registered StockFlow account was found for that information."
            );
        }


        if (
            code === "RECOVERY_IDENTITY_MISSING"
        ) {

            return (
                "Please provide your registered Gmail, phone number, or username."
            );
        }


        /*
         * OTP errors.
         */

        if (
            code === "INVALID_OTP" ||
            code === "OTP_INVALID"
        ) {

            return (
                "The recovery code is incorrect. Please try again."
            );
        }


        if (
            code === "OTP_EXPIRED"
        ) {

            return (
                "The recovery code has expired. Please request a new code."
            );
        }


        if (
            code === "OTP_LOCKED" ||
            code === "ACCOUNT_LOCKED"
        ) {

            return (
                "Recovery verification is temporarily locked. Please try again later."
            );
        }


        if (
            code === "MAX_ATTEMPTS"
        ) {

            return (
                "You have reached the maximum number of recovery attempts. Please try again later."
            );
        }


        if (
            code === "OTP_COOLDOWN"
        ) {

            return (
                "Please wait before requesting another recovery code."
            );
        }


        /*
         * Transport errors.
         */

        if (
            code === "NETWORK_ERROR" ||
            code === "HTTP_ERROR" ||
            code === "API_URL_MISSING" ||
            code === "API_URL_INVALID" ||
            code === "EMPTY_RESPONSE" ||
            code === "INVALID_JSON"
        ) {

            return (
                "Unable to connect to the recovery service. Please try again."
            );
        }


        if (
            code === "TIMEOUT"
        ) {

            return (
                "The recovery service took too long to respond. Please try again."
            );
        }


        if (
            error.name === "AbortError"
        ) {

            return (
                "The recovery service took too long to respond. Please try again."
            );
        }


        /*
         * ALWAYS preserve a legitimate backend message.
         */

        if (message) {

            return message;
        }


        return (
            "Something went wrong. Please try again."
        );
    }


    /* =====================================================
       DISPLAY DESTINATION
       ===================================================== */

    function displayDestination() {

        if (!recoveryDestination) {

            return;
        }


        const identity =
            resolveIdentity();


        if (!identity) {

            recoveryDestination.textContent =
                "Enter your registered Gmail, phone number, or username.";

            return;
        }


        let display =
            identity;


        if (
            identity.includes("@")
        ) {

            display =
                maskEmail(
                    identity
                );

        } else if (
            /^\+?\d+$/.test(
                identity.replace(
                    /[\s()-]/g,
                    ""
                )
            )
        ) {

            display =
                maskPhone(
                    identity
                );
        }


        recoveryDestination.textContent =
            display;
    }


    /* =====================================================
       MASK EMAIL
       ===================================================== */

    function maskEmail(email) {

        const value =
            clean(email);


        const at =
            value.indexOf("@");


        if (at <= 0) {

            return value;
        }


        const name =
            value.slice(
                0,
                at
            );


        const domain =
            value.slice(
                at
            );


        if (
            name.length <= 2
        ) {

            return (
                name.charAt(0) +
                "*" +
                domain
            );
        }


        return (
            name.charAt(0) +
            "*".repeat(
                Math.min(
                    name.length - 1,
                    4
                )
            ) +
            domain
        );
    }


    /* =====================================================
       MASK PHONE
       ===================================================== */

    function maskPhone(phone) {

        const value =
            clean(phone)
                .replace(
                    /[\s()-]/g,
                    ""
                );


        if (
            value.length <= 4
        ) {

            return value;
        }


        return (
            "*".repeat(
                Math.max(
                    0,
                    value.length - 4
                )
            ) +
            value.slice(-4)
        );
    }


