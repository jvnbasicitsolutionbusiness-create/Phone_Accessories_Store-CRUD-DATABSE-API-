    /* =====================================================
       PASSWORD VALIDATION
       ===================================================== */

    function validatePassword(password) {

        const value =
            clean(password);


        return {

            length:
                value.length >= 8,

            uppercase:
                /[A-Z]/.test(value),

            lowercase:
                /[a-z]/.test(value),

            number:
                /[0-9]/.test(value),

            symbol:
                /[^A-Za-z0-9]/.test(value)
        };
    }


    /* =====================================================
       PASSWORD STRENGTH
       ===================================================== */

    function getPasswordStrength(password) {

        const checks =
            validatePassword(
                password
            );


        let score = 0;


        if (checks.length) {
            score++;
        }


        if (checks.uppercase) {
            score++;
        }


        if (checks.lowercase) {
            score++;
        }


        if (checks.number) {
            score++;
        }


        if (checks.symbol) {
            score++;
        }


        return {

            score,

            total: 5,

            checks
        };
    }


    /* =====================================================
       PASSWORD METER
       ===================================================== */

    function updatePasswordMeter() {

        if (!newPassword) {

            return;
        }


        const password =
            newPassword.value;


        const result =
            getPasswordStrength(
                password
            );


        if (recoveryPasswordBar) {

            const percentage =
                (
                    result.score /
                    result.total
                ) *
                100;


            recoveryPasswordBar.style.width =
                percentage + "%";
        }


        if (recoveryPasswordHint) {

            if (!password) {

                recoveryPasswordHint.textContent =
                    "Use 8+ characters with uppercase, lowercase, number and symbol.";

            } else if (
                result.score <= 2
            ) {

                recoveryPasswordHint.textContent =
                    "Weak password. Add uppercase, lowercase, number and symbol.";

            } else if (
                result.score === 3
            ) {

                recoveryPasswordHint.textContent =
                    "Moderate password. Add more complexity.";

            } else if (
                result.score === 4
            ) {

                recoveryPasswordHint.textContent =
                    "Strong password. One more requirement is recommended.";

            } else {

                recoveryPasswordHint.textContent =
                    "Strong password.";
            }
        }
    }


    /* =====================================================
       PASSWORD FORM VALIDATION
       ===================================================== */

    function validateNewPasswordForm() {

        const password =
            newPassword
                ? newPassword.value
                : "";


        const confirm =
            confirmNewPassword
                ? confirmNewPassword.value
                : "";


        const result =
            getPasswordStrength(
                password
            );


        if (!password) {

            return {

                valid: false,

                message:
                    "Please enter a new password."
            };
        }


        if (
            !result.checks.length ||
            !result.checks.uppercase ||
            !result.checks.lowercase ||
            !result.checks.number ||
            !result.checks.symbol
        ) {

            return {

                valid: false,

                message:
                    "Password must contain at least 8 characters, uppercase, lowercase, number, and symbol."
            };
        }


        if (!confirm) {

            return {

                valid: false,

                message:
                    "Please confirm your new password."
            };
        }


        if (
            password !==
            confirm
        ) {

            return {

                valid: false,

                message:
                    "Passwords do not match."
            };
        }


        return {

            valid: true,

            message: ""
        };
    }


    /* =====================================================
       RESET PASSWORD
       ===================================================== */

    async function resetPassword() {

        if (
            state.resetting
        ) {

            return;
        }


        if (
            !state.recoveryVerified
        ) {

            showMessage(
                passwordMessage,
                "Please verify your recovery code first.",
                "error"
            );

            return;
        }


        const validation =
            validateNewPasswordForm();


        if (!validation.valid) {

            showMessage(
                passwordMessage,
                validation.message,
                "error"
            );

            return;
        }


        if (!API) {

            showMessage(
                passwordMessage,
                "The recovery service is not available.",
                "error"
            );

            return;
        }


        state.resetting =
            true;


        if (resetPasswordButton) {

            resetPasswordButton.disabled =
                true;


            resetPasswordButton.dataset.originalText =
                resetPasswordButton.dataset.originalText ||
                resetPasswordButton.textContent;


            resetPasswordButton.textContent =
                "Resetting...";
        }


        hideMessage(
            passwordMessage
        );


        try {

            await API.resetPassword({

                uid:
                    state.uid,

                identity:
                    resolveIdentity(),

                username:
                    state.username,

                email:
                    state.email,

                gmail:
                    state.gmail,

                phone:
                    state.phone,

                newPassword:
                    newPassword.value,

                password:
                    newPassword.value,

                confirmPassword:
                    confirmNewPassword.value
            });


            /*
             * Clear recovery state.
             */

            state.backendOtp =
                "";


            state.otpReady =
                false;


            state.otpVerified =
                false;


            state.recoveryVerified =
                false;


            storageRemove(
                STORAGE_KEYS.IDENTITY
            );


            storageRemove(
                STORAGE_KEYS.USERNAME
            );


            storageRemove(
                STORAGE_KEYS.EMAIL
            );


            storageRemove(
                STORAGE_KEYS.PHONE
            );


            storageRemove(
                STORAGE_KEYS.UID
            );


            storageRemove(
                STORAGE_KEYS.CHANNEL
            );


            storageRemove(
                STORAGE_KEYS.RECOVERY_READY
            );


            storageRemove(
                STORAGE_KEYS.RECOVERY_OTP
            );


            storageRemove(
                STORAGE_KEYS.RECOVERY_STARTED
            );


            storageRemove(
                STORAGE_KEYS.TOKEN
            );


            storageRemove(
                STORAGE_KEYS.USER
            );


            showMessage(
                passwordMessage,
                "Your password has been successfully updated.",
                "success"
            );


            showStep(
                "success"
            );


        } catch (error) {

            console.error(
                "[STOCKFLOW RECOVERY] Password reset failed:",
                error
            );


            showMessage(
                passwordMessage,
                getErrorMessage(error),
                "error"
            );


        } finally {

            state.resetting =
                false;


            if (resetPasswordButton) {

                resetPasswordButton.disabled =
                    false;


                resetPasswordButton.textContent =
                    resetPasswordButton.dataset.originalText ||
                    "Reset password";
            }
        }
    }


    /* =====================================================
       PASSWORD TOGGLES
       ===================================================== */

    function initializePasswordToggles() {

        const buttons =
            document.querySelectorAll(
                ".password-toggle"
            );


        buttons.forEach(
            function (button) {

                button.addEventListener(
                    "click",
                    function () {

                        const targetId =
                            button.dataset.target;


                        const input =
                            targetId
                                ? $(targetId)
                                : null;


                        if (!input) {

                            return;
                        }


                        if (
                            input.type ===
                            "password"
                        ) {

                            input.type =
                                "text";


                            button.textContent =
                                "Hide";

                        } else {

                            input.type =
                                "password";


                            button.textContent =
                                "Show";
                        }
                    }
                );
            }
        );
    }


