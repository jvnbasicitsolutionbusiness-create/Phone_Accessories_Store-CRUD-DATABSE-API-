    /* =========================================================
       HEALTH CHECK
       ========================================================= */

    async function health() {

        validateApiUrl();


        const controller =
            new AbortController();


        const timeout =
            setTimeout(

                () => {

                    controller.abort();

                },

                REQUEST_TIMEOUT
            );


        try {

            const response =
                await fetch(

                    API_URL,

                    {

                        method:
                            "GET",

                        redirect:
                            "follow",

                        signal:
                            controller.signal
                    }
                );


            const text =
                await response.text();


            if (
                !text ||
                !text.trim()
            ) {

                return {

                    success:
                        response.ok,

                    code:
                        response.ok
                            ? "EMPTY_RESPONSE"
                            : "HTTP_ERROR",

                    message:
                        response.ok

                            ? "Empty health response."

                            : `Health check returned HTTP ${response.status}.`
                };
            }


            try {

                return JSON.parse(
                    text
                );

            } catch (_) {

                return {

                    success:
                        response.ok,

                    code:
                        response.ok
                            ? "INVALID_JSON"
                            : "HTTP_ERROR",

                    message:
                        response.ok

                            ? "Health check returned invalid JSON."

                            : `Health check returned HTTP ${response.status}.`,

                    raw:
                        text
                };
            }


        } catch (error) {

            if (
                error?.name ===
                "AbortError"
            ) {

                throw new StockFlowAPIError(

                    "Unable to reach the StockFlow backend because the health check timed out.",

                    "TIMEOUT",

                    {

                        originalError:
                            error,

                        isTransportError:
                            true
                    }
                );
            }


            throw new StockFlowAPIError(

                "Unable to reach the StockFlow backend.",

                "HEALTH_CHECK_FAILED",

                {

                    originalError:
                        error,

                    isTransportError:
                        true
                }
            );

        } finally {

            clearTimeout(
                timeout
            );
        }
    }


