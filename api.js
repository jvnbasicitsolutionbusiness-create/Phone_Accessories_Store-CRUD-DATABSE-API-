    /* =========================================================
       OTP — VERIFY
       ========================================================= */

    async function verifyOtp(
        data = {}
    ) {

        const channel =
            safeString(

                data.channel ||

                data.otpChannel

            ).toLowerCase() ||
            "email";


        const normalizedChannel =
            channel === "phone"
                ? "phone"
                : "email";


        const payload = {

            uid:
                safeString(
                    data.uid
                ),

            identity:
                buildIdentity(
                    data
                ),

            username:
                safeString(
                    data.username
                ),

            email:
                safeString(
                    data.email
                ),

            gmail:
                safeString(
                    data.gmail ||
                    data.email
                ),

            phone:
                safeString(
                    data.phone
                ),

            channel:
                normalizedChannel,

            otpChannel:
                normalizedChannel,

            /*
             * IMPORTANT:
             *
             * This is the OTP entered manually by the user.
             *
             * It is NOT generated here.
             */

            otp:
                safeString(
                    data.otp
                )
        };


        try {

            const result =
                await request(
                    "verifyOtp",
                    payload
                );


            return normalizeResult(
                result
            );


        } catch (error) {

            /*
             * Business errors should be returned to
             * verify.js so the user remains on verify.html.
             *
             * Examples:
             *
             * OTP_INVALID
             * OTP_EXPIRED
             * OTP_LOCKED
             * ACCOUNT_NOT_FOUND
             * ACCOUNT_DISABLED
             */

            if (
                error?.data &&
                error?.isTransportError !== true
            ) {

                return normalizeResult(
                    error.data
                );
            }


            throw error;
        }
    }


    /* =========================================================
       OTP — PREPARE
       ========================================================= */

    async function prepareOtp(
        data = {}
    ) {

        const channel =
            safeString(

                data.channel ||

                data.otpChannel

            ).toLowerCase() ||
            "email";


        const normalizedChannel =
            channel === "phone"
                ? "phone"
                : "email";


        const payload = {

            uid:
                safeString(
                    data.uid
                ),

            identity:
                buildIdentity(
                    data
                ),

            username:
                safeString(
                    data.username
                ),

            email:
                safeString(
                    data.email
                ),

            gmail:
                safeString(
                    data.gmail ||
                    data.email
                ),

            phone:
                safeString(
                    data.phone
                ),

            channel:
                normalizedChannel,

            otpChannel:
                normalizedChannel
        };


        try {

            const result =
                await request(

                    "prepareOtp",

                    payload
                );


            return normalizeResult(
                result
            );


        } catch (error) {

            /*
             * IMPORTANT:
             *
             * Business errors must be returned instead of
             * being mistaken for a connection failure.
             */

            if (
                error?.data &&
                error?.isTransportError !== true
            ) {

                return normalizeResult(
                    error.data
                );
            }


            const code =
                getServerErrorCode(
                    error
                );


            const message =
                String(

                    getServerErrorMessage(
                        error
                    ) ||

                    error?.message ||

                    ""

                ).toLowerCase();


            /*
             * Compatibility with older Apps Script versions
             * which may not have prepareOtp.
             *
             * Only use resendOtp when the backend genuinely
             * reports an unknown/unsupported action.
             */

            const missingAction =
                code ===
                    "UNKNOWN_ACTION" ||

                message.includes(
                    "unknown action"
                ) ||

                message.includes(
                    "unsupported action"
                ) ||

                message.includes(
                    "action not found"
                );


            if (
                missingAction
            ) {

                try {

                    const fallback =
                        await request(

                            "resendOtp",

                            payload
                        );


                    return normalizeResult(
                        fallback
                    );


                } catch (fallbackError) {

                    if (
                        fallbackError?.data &&
                        fallbackError?.isTransportError !== true
                    ) {

                        return normalizeResult(
                            fallbackError.data
                        );
                    }


                    throw fallbackError;
                }
            }


            throw error;
        }
    }


