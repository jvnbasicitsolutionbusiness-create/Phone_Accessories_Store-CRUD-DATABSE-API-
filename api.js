    const REQUEST_TIMEOUT =
        Number(
            API_CONFIG.TIMEOUT ||
            CONFIG.API_TIMEOUT ||
            30000
        );

    const RETRY_COUNT =
        Number(
            API_CONFIG.RETRY ||
            CONFIG.API_RETRY ||
            0
        );

    const RETRY_DELAY =
        Number(
            API_CONFIG.RETRY_DELAY ||
            CONFIG.API_RETRY_DELAY ||
            1000
        );

    const CONTENT_TYPE =
        API_CONFIG.CONTENT_TYPE ||
        "text/plain;charset=utf-8";


    /* =========================================================
       ERROR CLASS
       ========================================================= */

    class StockFlowAPIError extends Error {

        constructor(
            message,
            code = "API_ERROR",
            details = null
        ) {

            super(
                message ||
                "StockFlow API error."
            );

            this.name =
                "StockFlowAPIError";

            this.code =
                code ||
                "API_ERROR";

            this.details =
                details;

            this.status =
                details?.status ??
                null;

            this.action =
                details?.action ??
                null;

            this.data =
                details?.data ??
                null;

            this.response =
                details?.response ??
                null;

            this.rawResponse =
                details?.rawResponse ??
                null;

            this.originalError =
                details?.originalError ??
                null;

            this.isTransportError =
                details?.isTransportError === true;
        }
    }


    /* =========================================================
       BASIC HELPERS
       ========================================================= */

    function safeString(value) {

        if (
            value === null ||
            value === undefined
        ) {
            return "";
        }

        return String(value).trim();
    }


    function parsePossibleObject(value) {

        if (!value) {
            return null;
        }

        if (
            typeof value === "object"
        ) {
            return value;
        }

        if (
            typeof value === "string"
        ) {

            try {

                return JSON.parse(
                    value
                );

            } catch (_) {

                return null;
            }
        }

        return null;
    }


    function getNestedObjectCandidates(value) {

        const candidates = [];

        if (!value) {
            return candidates;
        }

        const direct =
            parsePossibleObject(value);

        if (direct) {
            candidates.push(direct);
        }

        if (
            direct &&
            direct.data
        ) {

            const data =
                parsePossibleObject(
                    direct.data
                );

            if (data) {
                candidates.push(data);
            }
        }

        if (
            direct &&
            direct.response
        ) {

            const response =
                parsePossibleObject(
                    direct.response
                );

            if (response) {
                candidates.push(response);
            }
        }

        if (
            direct &&
            direct.result
        ) {

            const result =
                parsePossibleObject(
                    direct.result
                );

            if (result) {
                candidates.push(result);
            }
        }

        return candidates;
    }


    function getServerErrorCode(error) {

        if (!error) {
            return "";
        }


        /* -----------------------------------------------------
           Direct code
           ----------------------------------------------------- */

        if (
            error.code
        ) {

            return safeString(
                error.code
            );
        }


        /* -----------------------------------------------------
           Nested common locations
           ----------------------------------------------------- */

        const directCandidates = [
            error.data,
            error.response,
            error.result,
            error.details,
            error.rawResponse
        ];


        for (
            const candidate
            of directCandidates
        ) {

            const objects =
                getNestedObjectCandidates(
                    candidate
                );

            for (
                const object
                of objects
            ) {

                if (
                    object &&
                    object.code
                ) {

                    return safeString(
                        object.code
                    );
                }
            }
        }


        return "";
    }


    function getServerErrorMessage(error) {

        if (!error) {
            return "";
        }


        /* -----------------------------------------------------
           IMPORTANT:
           Only use meaningful messages.
           ----------------------------------------------------- */

        const directMessage =
            error.message;

        if (
            directMessage &&
            !(
                error instanceof
                StockFlowAPIError
            ) ||
            (
                directMessage &&
                error.code &&
                error.code !==
                    "NETWORK_ERROR"
            )
        ) {

            return safeString(
                directMessage
            );
        }


        const directCandidates = [
            error.data,
            error.response,
            error.result,
            error.details,
            error.rawResponse
        ];


        for (
            const candidate
            of directCandidates
        ) {

            const objects =
                getNestedObjectCandidates(
                    candidate
                );

            for (
                const object
                of objects
            ) {

                if (
                    object &&
                    object.message
                ) {

                    return safeString(
                        object.message
                    );
                }

                if (
                    object &&
                    object.error
                ) {

                    return safeString(
                        object.error
                    );
                }
            }
        }


        return "";
    }


    function normalizeResult(result) {

        if (
            result === null ||
            result === undefined
        ) {

            return {
                success: false,
                code: "EMPTY_RESPONSE",
                message:
                    "Empty server response."
            };
        }


        if (
            typeof result ===
            "string"
        ) {

            const parsed =
                parsePossibleObject(
                    result
                );

            if (parsed) {
                return parsed;
            }
        }


        return result;
    }


