    /* =====================================================
       MASK EMAIL
       ===================================================== */

    function maskEmail(email) {

        const value =
            String(
                email || ""
            ).trim();


        const parts =
            value.split("@");


        if (
            parts.length !== 2
        ) {

            return value;
        }


        const name =
            parts[0];


        const domain =
            parts[1];


        if (
            name.length <= 2
        ) {

            return (
                name.charAt(0) +
                "*" +
                "@" +
                domain
            );
        }


        return (
            name.substring(
                0,
                2
            ) +
            "*".repeat(
                Math.max(
                    2,
                    name.length - 2
                )
            ) +
            "@" +
            domain
        );
    }


    /* =====================================================
       MASK PHONE
       ===================================================== */

    function maskPhone(phone) {

        const value =
            String(
                phone || ""
            ).replace(
                /\s+/g,
                ""
            );


        if (
            value.length < 7
        ) {

            return value;
        }


        return (
            value.substring(
                0,
                3
            ) +
            "****" +
            value.substring(
                value.length - 3
            )
        );
    }


