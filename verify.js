    /* =====================================================
       DEMO DELAY
       ===================================================== */

    function getDemoDelay() {

        const min =
            Math.max(
                0,
                DEMO_MIN_DELAY
            );


        const max =
            Math.max(
                min,
                DEMO_MAX_DELAY
            );


        if (
            max <= min
        ) {

            return min;
        }


        /*
         * IMPORTANT:
         *
         * This random value ONLY determines
         * how long the UI waits.
         *
         * It NEVER creates the OTP.
         */

        return (
            min +
            Math.floor(
                Math.random() *
                (
                    max -
                    min +
                    1
                )
            )
        );
    }


    function wait(
        milliseconds
    ) {

        return new Promise(
            resolve =>
                setTimeout(
                    resolve,
                    milliseconds
                )
        );
    }


    /* =====================================================
       AUTO-FILL BACKEND OTP
       ===================================================== */

    async function autoFillBackendOtp(
        response
    ) {

        if (!DEMO_MODE) {
            return;
        }


        const otp =
            extractOtp(
                response
            );


        if (
            otp.length !== OTP_LENGTH
        ) {

            console.warn(
                "[STOCKFLOW VERIFY] Backend did not return a demo OTP."
            );

            return;
        }


        state.demoOtp =
            otp;


        state.otpReady =
            true;


        /*
         * DELAY STARTS HERE.
         *
         * This function is called ONLY from
         * verify.html after prepareOtp()
         * succeeds.
         *
         * Registration itself does NOT wait.
         */

        const delay =
            getDemoDelay();


        console.log(
            "[STOCKFLOW VERIFY] Demo OTP received from backend. Auto-fill delay:",
            delay,
            "ms"
        );


        if (verificationDescription) {

            verificationDescription.textContent =
                "Verification code sent. Preparing the code...";
        }


        await wait(
            delay
        );


        /*
         * Make sure the user has not already
         * requested another code.
         */

        if (
            !state.requesting &&
            state.otpReady &&
            state.demoOtp === otp
        ) {

            fillOtp(
                otp
            );


            if (verificationDescription) {

                verificationDescription.textContent =
                    "Your verification code is ready.";
            }
        }
    }


